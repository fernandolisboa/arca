import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { PinnedFileRow, RuleRows } from '../src/rule-rows.ts';
import { buildKnowledge, formatIssue } from './build.ts';
import type { CalendarDate } from '@arca/domain';
import { parseCalendarDate } from '@arca/domain';

/** The migration that imports the repository's rules into the database once (ADR-0031). */
export const importMigration = 'knowledge_rule_import';

/**
 * The build date the import was generated at: the data must validate as it did then, so the
 * committed migration can be generated again and compared.
 */
export const importDate: CalendarDate = parseCalendarDate('2026-11-16');

const literal = (value: string): string => `'${value.replaceAll("'", "''")}'`;
const json = (value: unknown): string => `${literal(JSON.stringify(value))}::jsonb`;

interface Table {
  readonly name: string;
  readonly what: string;
  readonly idColumn: string;
  readonly keys: readonly (readonly [string, number, string])[];
}

const tables = (rows: RuleRows): Table[] => {
  const keysOf = (pinned: readonly PinnedFileRow[]) =>
    pinned.map(({ id, number, contentHash }) => [id, number, contentHash] as const);
  return [
    {
      name: 'official_domain_list',
      what: 'official-domain list',
      idColumn: 'list_id',
      keys: keysOf(rows.officialDomainLists),
    },
    {
      name: 'country_set',
      what: 'country set',
      idColumn: 'set_id',
      keys: keysOf(rows.countrySets),
    },
    {
      name: 'route_version',
      what: 'route version',
      idColumn: 'route_id',
      keys: rows.routeVersions.map(({ routeId, number, contentHash }) => [
        routeId,
        number,
        contentHash,
      ]),
    },
  ];
};

/**
 * The import as SQL: first a check that every row already stored under an imported ID and number
 * has the imported hash, which aborts the migration otherwise; then the inserts, which keep a row
 * already stored. Running it again changes nothing.
 */
export function importSql(rows: RuleRows): string {
  const checks = tables(rows).map(
    ({ name, what, idColumn, keys }) => `  IF EXISTS (
    SELECT FROM (VALUES
${keys.map(([id, number, hash]) => `      (${literal(id)}, ${String(number)}, ${literal(hash)})`).join(',\n')}
    ) AS imported (id, number, content_hash)
    JOIN "knowledge"."${name}" AS stored
      ON stored.${idColumn} = imported.id AND stored.number = imported.number
    WHERE stored.content_hash <> imported.content_hash
  ) THEN
    RAISE EXCEPTION 'knowledge import: a stored ${what} has another content hash';
  END IF;`,
  );
  const [lists, sets, routes] = tables(rows);
  if (lists === undefined || sets === undefined || routes === undefined) throw new Error('Tables');
  const pinnedInsert = ({ name, idColumn }: Table, pinned: readonly PinnedFileRow[]) =>
    `INSERT INTO "knowledge"."${name}" (${idColumn}, number, content, content_hash) VALUES
${pinned.map((row) => `  (${literal(row.id)}, ${String(row.number)}, ${json(row.content)}, ${literal(row.contentHash)})`).join(',\n')}
ON CONFLICT (${idColumn}, number) DO NOTHING;`;
  return [
    `-- Generated by packages/knowledge/scripts/rule-import.ts from the data directory. Do not edit.
-- The one-time import of every route version, country set and official-domain list into the
-- database, each with the hash the knowledge build computed (ADR-0031). A row already stored is
-- kept; a stored row with another hash aborts the import. It writes no decision: states stay
-- computed from knowledge.decision.
DO $check$
BEGIN
${checks.join('\n')}
END
$check$;`,
    pinnedInsert(lists, rows.officialDomainLists),
    pinnedInsert(sets, rows.countrySets),
    `INSERT INTO "knowledge"."${routes.name}" (${routes.idColumn}, number, content, content_hash, cases) VALUES
${rows.routeVersions.map((row) => `  (${literal(row.routeId)}, ${String(row.number)}, ${json(row.content)}, ${literal(row.contentHash)}, ${row.cases === null ? 'NULL' : json(row.cases)})`).join(',\n')}
ON CONFLICT (${routes.idColumn}, number) DO NOTHING;`,
  ]
    .join('\n--> statement-breakpoint\n')
    .concat('\n');
}

/** The import migration's folder under `packages/db/migrations`. */
export async function importMigrationFile(migrationsDir: string): Promise<string> {
  const folder = (await readdir(migrationsDir)).find((name) =>
    name.endsWith(`_${importMigration}`),
  );
  if (folder === undefined) throw new Error(`No ${importMigration} migration folder`);
  return join(migrationsDir, folder, 'migration.sql');
}

/** The import's SQL from the repository's data directory, which must build without issues. */
export async function generatedImport(dataDir: string): Promise<string> {
  const { issues, rows } = await buildKnowledge(dataDir, importDate);
  if (issues.length > 0) throw new Error(issues.map(formatIssue).join('\n'));
  return importSql(rows);
}

async function main(): Promise<void> {
  const packageDir = fileURLToPath(new URL('..', import.meta.url));
  const target = await importMigrationFile(join(packageDir, '..', 'db', 'migrations'));
  await writeFile(target, await generatedImport(join(packageDir, 'data')));
  process.stdout.write(`Wrote ${target}\n`);
}

if (import.meta.main) await main();
