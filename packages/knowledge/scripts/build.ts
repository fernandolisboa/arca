import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type CalendarDate, parseCalendarDate } from '@arca/domain';
import { checkHashes } from './hashes.ts';
import { type Issue, loadData } from './load.ts';
import { type BuiltEntry, validateData } from './validate.ts';

export interface KnowledgeBuild {
  readonly entries: readonly BuiltEntry[];
  readonly issues: readonly Issue[];
}

/** Loads, validates and hashes the data directory (spec 0002, R6). Any issue fails the build. */
export async function buildKnowledge(
  dataDir: string,
  buildDate: CalendarDate,
): Promise<KnowledgeBuild> {
  const raw = await loadData(dataDir);
  const validated = validateData(raw, buildDate);
  return {
    entries: validated.entries,
    issues: [...validated.issues, ...checkHashes(raw.hashes, validated.hashes, validated.hashable)],
  };
}

/**
 * The generated module. The data goes through JSON.parse rather than an object literal, so a
 * `__proto__` key stays data, and the runtime entry validates it again before use.
 */
export function catalogModule(entries: readonly BuiltEntry[]): string {
  return [
    '// Generated by scripts/build.ts from data/. Do not edit; it is not checked in.',
    `export const catalogData: unknown = JSON.parse(${JSON.stringify(JSON.stringify(entries))});`,
    '',
  ].join('\n');
}

export function formatIssue(issue: Issue): string {
  return `${issue.file}${issue.path === undefined ? '' : ` ${issue.path}`}: ${issue.message}`;
}

async function main(): Promise<void> {
  const packageDir = fileURLToPath(new URL('..', import.meta.url));
  const today = parseCalendarDate(new Date().toISOString().slice(0, 10));
  const target = join(packageDir, 'src', 'generated', 'catalog.ts');
  const { entries, issues } = await buildKnowledge(join(packageDir, 'data'), today);
  if (issues.length > 0) {
    // A catalog from an earlier build would otherwise still be served by tools run outside Turbo.
    await rm(target, { force: true });
    process.stderr.write(`${issues.map(formatIssue).join('\n')}\n`);
    process.exitCode = 1;
    return;
  }
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, catalogModule(entries));
  process.stdout.write(`Knowledge catalog: ${String(entries.length)} route versions\n`);
}

if (import.meta.main) await main();
