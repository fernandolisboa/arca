import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  type CalendarDate,
  type RuleCaseSummary,
  maxKnowledgeJsonDepth,
  parseCalendarDate,
} from '@arca/domain';
import { parseJsonSubset } from '@arca/scripts/json';
import { casesFileSchema } from './cases.ts';
import { checkHashes } from './hashes.ts';
import { type Issue, type RawData, loadData, readKnowledgeFile } from './load.ts';
import {
  type BuiltEntry,
  type PinnedCountries,
  type ValidationOptions,
  validateData,
} from './validate.ts';

/** The current cases of one version, without their snapshots, for the activation screen. */
export interface BuiltCases {
  readonly hash: string;
  readonly cases: readonly RuleCaseSummary[];
}

export interface KnowledgeBuild {
  readonly entries: readonly BuiltEntry[];
  readonly countries: PinnedCountries;
  readonly cases: readonly BuiltCases[];
  readonly issues: readonly Issue[];
}

const casesPath = /^routes\/([a-z0-9-]+\/[1-9][0-9]*)\.cases\.json$/;

/**
 * Each version's current cases, summarized. The cases runner checks the files and fails on one it
 * cannot read; here such a file is left out, so the screen shows no cases rather than half of them.
 */
async function caseSummaries(
  dataDir: string,
  raw: RawData,
  hashes: ReadonlyMap<string, string>,
): Promise<BuiltCases[]> {
  const cases: BuiltCases[] = [];
  for (const file of raw.cases) {
    const hash = hashes.get(`routes/${casesPath.exec(file)?.[1] ?? ''}`);
    if (hash === undefined) continue;
    let parsed;
    try {
      parsed = casesFileSchema.safeParse(
        parseJsonSubset(await readKnowledgeFile(join(dataDir, file)), maxKnowledgeJsonDepth),
      );
    } catch {
      continue;
    }
    if (!parsed.success) continue;
    const superseded = new Set(parsed.data.cases.flatMap((entry) => entry.supersedes ?? []));
    cases.push({
      hash,
      cases: parsed.data.cases
        .filter((entry) => !superseded.has(entry.id))
        .map(({ id, principal, rulesAsOf, expected }) => ({ id, principal, rulesAsOf, expected })),
    });
  }
  return cases;
}

/** Loads, validates and hashes the data directory (spec 0002, R6). Any issue fails the build. */
export async function buildKnowledge(
  dataDir: string,
  buildDate: CalendarDate,
  options: ValidationOptions = {},
): Promise<KnowledgeBuild> {
  const raw = await loadData(dataDir);
  const validated = validateData(raw, buildDate, options);
  return {
    entries: validated.entries,
    countries: validated.countries,
    cases: await caseSummaries(dataDir, raw, validated.hashes),
    issues: [...validated.issues, ...checkHashes(raw.hashes, validated.hashes, validated.hashable)],
  };
}

/**
 * The generated module. The data goes through JSON.parse rather than an object literal, so a
 * `__proto__` key stays data, and the runtime entry validates it again before use.
 */
export function catalogModule(
  entries: readonly BuiltEntry[],
  countries: PinnedCountries = { countries: [], formerCountries: [] },
  cases: readonly BuiltCases[] = [],
): string {
  return [
    '// Generated by scripts/build.ts from data/. Do not edit; it is not checked in.',
    `export const catalogData: unknown = JSON.parse(${JSON.stringify(JSON.stringify(entries))});`,
    `export const countryData: unknown = JSON.parse(${JSON.stringify(JSON.stringify(countries))});`,
    `export const caseData: unknown = JSON.parse(${JSON.stringify(JSON.stringify(cases))});`,
    '',
  ].join('\n');
}

export function formatIssue(issue: Issue): string {
  return `${issue.file}${issue.path === undefined ? '' : ` ${issue.path}`}: ${issue.message}`;
}

/** Today's date in UTC: the build date of the real catalog. */
export function todayUtc(): CalendarDate {
  return parseCalendarDate(new Date().toISOString().slice(0, 10));
}

async function main(): Promise<void> {
  const packageDir = fileURLToPath(new URL('..', import.meta.url));
  const today = todayUtc();
  const target = join(packageDir, 'src', 'generated', 'catalog.ts');
  // Removed first, so a failed or crashed build leaves no earlier catalog for tools outside Turbo.
  await rm(target, { force: true });
  const { entries, countries, cases, issues } = await buildKnowledge(
    join(packageDir, 'data'),
    today,
  );
  if (issues.length > 0) {
    process.stderr.write(`${issues.map(formatIssue).join('\n')}\n`);
    process.exitCode = 1;
    return;
  }
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, catalogModule(entries, countries, cases));
  process.stdout.write(`Knowledge catalog: ${String(entries.length)} route versions\n`);
}

if (import.meta.main) await main();
