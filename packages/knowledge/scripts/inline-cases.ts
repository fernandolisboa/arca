import { createHash } from 'node:crypto';
import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { caseSnapshotSchema, maxKnowledgeJsonDepth } from '@arca/domain';
import { parseJsonSubset } from '@arca/scripts/json';
import type { Json } from '../src/canonical.ts';
import { casesFileSchema } from '../src/cases.ts';
import type { RuleRows } from '../src/rule-rows.ts';
import { buildKnowledge, formatIssue } from './build.ts';
import { readKnowledgeFile } from './load.ts';
import { importDate } from './rule-import.ts';
import { json, literal } from './sql.ts';

/** The migration that rewrites imported cases that pin a synthetic family as inline snapshots. */
export const inlineCasesMigration = 'knowledge_inline_rule_cases';

/** One imported row whose cases pin a family, with the cases it stores and the inline ones. */
export interface InlinedRow {
  readonly routeId: string;
  readonly number: number;
  readonly contentHash: string;
  readonly imported: Json;
  readonly inlined: Json;
}

/**
 * Each imported row whose cases pin a family, with every pinned family replaced by the snapshot
 * its file holds, after checking the file against the pinned SHA-256, as the cases runner reads
 * it. A proposal's cases must be inline (ADR-0031), since the API has no families at run time.
 */
export async function inlinedRows(rows: RuleRows, familiesDir: string): Promise<InlinedRow[]> {
  const inlined: InlinedRow[] = [];
  for (const row of rows.routeVersions) {
    if (row.cases === null) continue;
    const parsed = casesFileSchema.parse(row.cases);
    if (parsed.cases.every((ruleCase) => ruleCase.family === undefined)) continue;
    const cases = [];
    for (const { family, ...ruleCase } of parsed.cases) {
      if (family === undefined) {
        cases.push(ruleCase);
        continue;
      }
      const bytes = await readKnowledgeFile(
        join(familiesDir, family.id, `${String(family.number)}.json`),
      );
      if (createHash('sha256').update(bytes).digest('hex') !== family.sha256) {
        throw new Error(`Family ${family.id} ${String(family.number)} does not hash as pinned`);
      }
      const snapshot = caseSnapshotSchema.parse(parseJsonSubset(bytes, maxKnowledgeJsonDepth));
      cases.push({ ...ruleCase, snapshot });
    }
    const file = casesFileSchema.parse({ ...parsed, cases });
    inlined.push({
      routeId: row.routeId,
      number: row.number,
      contentHash: row.contentHash,
      imported: row.cases,
      inlined: file as unknown as Json,
    });
  }
  return inlined;
}

/**
 * The rewrite as SQL. Rule rows are insert-only (ADR-0031), so the migrator lends itself an
 * update of the cases column for this one statement and gives it up again. It aborts when a
 * passkey decision binds one of these versions' cases hash, since a new hash would withdraw that
 * approval; it rewrites a row only while it stores the imported cases and has the imported hash;
 * and it aborts if any row still pins a family afterwards. Content, hashes and decisions stay.
 */
export function inlineCasesSql(rows: readonly InlinedRow[]): string {
  const keys = rows
    .map(({ routeId, number }) => `      (${literal(routeId)}, ${String(number)})`)
    .join(',\n');
  return [
    `-- Generated by packages/knowledge/scripts/inline-cases.ts from the data directory and
-- eval/families. Do not edit. Imported cases that pinned a synthetic family become inline
-- snapshots of that very family, so every route accepts update requests and edits (ADR-0031).
DO $check$
BEGIN
  IF EXISTS (
    SELECT FROM (VALUES
${keys}
    ) AS imported (route_id, number)
    JOIN "knowledge"."decision" AS decided
      ON decided.subject_kind = 'route' AND decided.route_id = imported.route_id
      AND decided.version_number = imported.number AND decided.cases_hash IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'knowledge inline cases: a passkey decision binds these cases';
  END IF;
END
$check$;`,
    'GRANT UPDATE ("cases") ON "knowledge"."route_version" TO app_migrator;',
    `CREATE POLICY "route_version_inline_cases" ON "knowledge"."route_version" AS PERMISSIVE FOR UPDATE TO "app_migrator" USING (true) WITH CHECK (true);`,
    `UPDATE "knowledge"."route_version" AS stored SET cases = rewritten.inlined FROM (VALUES
${rows
  .map(
    (row) =>
      `  (${literal(row.routeId)}, ${String(row.number)}, ${literal(row.contentHash)}, ${json(row.imported)}, ${json(row.inlined)})`,
  )
  .join(',\n')}
) AS rewritten (route_id, number, content_hash, imported, inlined)
WHERE stored.route_id = rewritten.route_id AND stored.number = rewritten.number
  AND stored.content_hash = rewritten.content_hash AND stored.cases = rewritten.imported;`,
    'DROP POLICY "route_version_inline_cases" ON "knowledge"."route_version";',
    'REVOKE UPDATE ON "knowledge"."route_version" FROM app_migrator;',
    `DO $check$
BEGIN
  IF EXISTS (
    SELECT FROM "knowledge"."route_version"
    WHERE pg_catalog.jsonb_path_exists(cases, '$.cases[*].family')
  ) THEN
    RAISE EXCEPTION 'knowledge inline cases: a route version still pins a family';
  END IF;
END
$check$;`,
  ]
    .join('\n--> statement-breakpoint\n')
    .concat('\n');
}

/** The rewrite migration's file under `packages/db/migrations`. */
export async function inlineCasesMigrationFile(migrationsDir: string): Promise<string> {
  const folder = (await readdir(migrationsDir)).find((name) =>
    name.endsWith(`_${inlineCasesMigration}`),
  );
  if (folder === undefined) throw new Error(`No ${inlineCasesMigration} migration folder`);
  return join(migrationsDir, folder, 'migration.sql');
}

/** The rows to rewrite, from the data directory the import read and the families it pins. */
export async function rowsToInline(dataDir: string, familiesDir: string): Promise<InlinedRow[]> {
  const { issues, rows } = await buildKnowledge(dataDir, importDate);
  if (issues.length > 0) throw new Error(issues.map(formatIssue).join('\n'));
  return inlinedRows(rows, familiesDir);
}

async function main(): Promise<void> {
  const packageDir = fileURLToPath(new URL('..', import.meta.url));
  const target = await inlineCasesMigrationFile(join(packageDir, '..', 'db', 'migrations'));
  const rows = await rowsToInline(
    join(packageDir, 'data'),
    join(packageDir, '..', '..', 'eval', 'families'),
  );
  await writeFile(target, inlineCasesSql(rows));
  process.stdout.write(`Wrote ${target} (${String(rows.length)} versions)\n`);
}

if (import.meta.main) await main();
