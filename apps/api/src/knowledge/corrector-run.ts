import type { Logger } from '@arca/telemetry';

/**
 * The owner's corrector run (ADR-0029), started from the app: the owner's scheduled task on
 * claude.ai, fired through its API trigger with the task's own token. The call carries no case or
 * personal data, only a fixed note that the app started it.
 */
export interface CorrectorRun {
  /** Fires the run; answers whether claude.ai accepted it. */
  readonly start: () => Promise<boolean>;
}

/** The owner's "Daily correction requests (Arca)" scheduled task (ADR-0029). */
export const correctorTaskId = 'trig_01EHDEQFbqCo4yAFZp9FQygC';

const endpoint = `https://api.anthropic.com/v1/claude_code/routines/${correctorTaskId}/fire`;
const timeoutMs = 10_000;

export interface RoutineSettings {
  /** The task's API trigger token, generated by the owner on claude.ai. */
  readonly token: string;
  readonly logger: Logger;
  readonly fetch?: typeof globalThis.fetch;
}

export function routineCorrectorRun({
  token,
  logger,
  fetch = globalThis.fetch,
}: RoutineSettings): CorrectorRun {
  return {
    async start() {
      try {
        const response = await fetch(endpoint, {
          method: 'POST',
          headers: {
            authorization: `Bearer ${token}`,
            'anthropic-beta': 'experimental-cc-routine-2026-04-01',
            'anthropic-version': '2023-06-01',
            'content-type': 'application/json',
          },
          body: JSON.stringify({ text: 'Started from the app by an owner-list admin.' }),
          redirect: 'error',
          signal: AbortSignal.timeout(timeoutMs),
        });
        await response.body?.cancel();
        if (!response.ok)
          logger.error({ errorCode: 'corrector_fire_refused', status: response.status });
        return response.ok;
      } catch (error) {
        logger.error({
          errorCode: 'corrector_fire_failed',
          errorName: error instanceof Error ? error.name : 'unknown',
        });
        return false;
      }
    },
  };
}
